# Builds src\Icons.g.cs from Font Awesome Free SVGs (only the icons Hallow Browser uses).
#   .\tools\gen-icons.ps1 -FaDir <path to fontawesome-free-*-desktop>
param([Parameter(Mandatory)] [string]$FaDir)
$solid = 'arrow-left arrow-right arrow-rotate-right xmark plus download magnifying-glass key lock lock-open shield-halved gamepad gear globe rotate-left up-right-from-square window-minimize window-maximize window-restore volume-high volume-xmark bars memory microchip gauge-high bolt moon pause play broom trash-can folder-open circle-info check minus music camera clapperboard house star triangle-exclamation arrows-rotate puzzle-piece magnifying-glass-plus magnifying-glass-minus chevron-up chevron-down eye fire bell wifi circle-half-stroke mobile-screen desktop sun table-columns tower-broadcast ellipsis-vertical layer-group briefcase table-list crop-simple expand book-open copy floppy-disk bookmark clock-rotate-left right-left angles-left angles-right font pen image chevron-right chevron-left text-width bars-staggered rectangle-list terminal folder folder-plus file-import file-export thumbtack mask sliders microphone video location-dot clipboard code cookie-bite newspaper gift ban plug display hard-drive calculator forward-step circle-check shield-virus computer-mouse heart-crack circle-play user user-plus users leaf note-sticky book-bookmark spell-check battery-quarter rocket volume-low table-cells-large circle check-double eye-slash square-plus film toggle-on toggle-off headphones' -split ' '
$brands = @('github', 'edge', 'discord', 'twitch', 'youtube', 'spotify', 'whatsapp')
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools\gen-icons.ps1 - do not edit.')
[void]$sb.AppendLine('// Icons: Font Awesome Free 7.3.1 by Fonticons, Inc. - https://fontawesome.com - licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).')
[void]$sb.AppendLine('using System.Collections.Generic;')
[void]$sb.AppendLine('namespace HallowBrowser')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    public static partial class Icons')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        // name -> SVG path data (Font Awesome viewBox height is 512)')
[void]$sb.AppendLine('        static readonly Dictionary<string, string> Data = new Dictionary<string, string> {')
foreach ($set in @(@{ dir = 'solid'; names = $solid }, @{ dir = 'brands'; names = $brands })) {
    foreach ($n in $set.names) {
        $svg = Get-Content (Join-Path $FaDir "svgs\$($set.dir)\$n.svg") -Raw
        $vb = [regex]::Match($svg, 'viewBox="0 0 (\d+) (\d+)"')
        $d = [regex]::Match($svg, ' d="([^"]+)"').Groups[1].Value
        # keep the true width: prepend an invisible move so the geometry bounds span the whole viewBox
        $w = $vb.Groups[1].Value; $h = $vb.Groups[2].Value; $path = "M0 0L0 0M$w ${h}L$w $h" + $d
        [void]$sb.AppendLine("            { `"$n`", `"$path`" },")
    }
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
$out = Join-Path $PSScriptRoot '..\src\Icons.g.cs'
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
"Wrote $out ($($solid.Count + $brands.Count) icons)"

